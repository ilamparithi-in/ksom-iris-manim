    ax.set_xlabel('PCA Component 1', color='#bdc3c7', fontsize=9)
    ax.set_ylabel('PCA Component 2', color='#bdc3c7', fontsize=9)
    ax.tick_params(colors='#bdc3c7', labelsize=8)
    for spine in ax.spines.values():
        spine.set_edgecolor('#555')


