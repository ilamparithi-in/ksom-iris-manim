import numpy as np
import matplotlib.pyplot as plt
import matplotlib.lines as mlines
from matplotlib.patches import Patch
from sklearn.datasets import load_iris
from sklearn.preprocessing import MinMaxScaler
from sklearn.decomposition import PCA


def load_and_preprocess():
    """
    Loading the Iris dataset, normalizing the features to [0, 1] range for better SOM training.
    """
    ### IRIS OUT ###
    iris = load_iris()
    X = iris.data.astype(np.float64)
    y = iris.target
    scaler = MinMaxScaler()
    X = scaler.fit_transform(X) # Fit and transform does this: X_scaled = (X - X.min(axis=0)) / (X.max(axis=0) - X.min(axis=0))
    # iris.target_names is the list of class names, like ['setosa', 'versicolor', 'virginica']
    return X, y, iris.target_names 
    

def initialize_weights(grid_x, grid_y, input_dim, seed=42):
    """
    Randomly selecting the initial weights, which represent the prototype vectors for each neuron in the SOM grid.
    """
    rng = np.random.default_rng(seed)
    return rng.random((grid_x, grid_y, input_dim))


def find_bmu(weights, x):
    """
    Best Matching Unit (BMU) is the neuron whose weight vector is closest to the input vector x.
    """
    diff = weights - x
    distances = np.linalg.norm(diff, axis=2) # Norm 2 distance, ie., Euclidean distance
    return np.unravel_index(np.argmin(distances), distances.shape) # oshiete oshieteyo sono shikumi wo


def compute_neighbourhood(grid_x, grid_y, bmu_idx, sigma):
    """
    Compute the value of Neighbourhood for each neuron based on its Euclidean distance to the BMU.
    Neighbourhood function used: Gaussian Function
    """
    bmu_r, bmu_c = bmu_idx
    r = np.arange(grid_x) # r for row
    c = np.arange(grid_y) # c for column
    cc, rr = np.meshgrid(c, r) # som grid 
    d2 = (rr - bmu_r) ** 2 + (cc - bmu_c) ** 2
    return np.exp(-d2 / (2.0 * sigma ** 2))


def update_weights(weights, x, bmu_idx, alpha, sigma):
    """
    WEIGHT UPDATION 🗣️🗣️🗣️🗣️🗣️
    """
    grid_x, grid_y, _ = weights.shape
    h = compute_neighbourhood(grid_x, grid_y, bmu_idx, sigma)
    weights += alpha * h[:, :, np.newaxis] * (x - weights)
    return weights


def decay_parameters(t, n_iterations, alpha_init, sigma_init):
    """
    As the training progresses, both the learning rate (alpha) and the neighbourhood radius (sigma) decay exponentially.
    This allows the SOM to make large adjustments in the early stages and fine-tune in later stages.
    """
    tau = n_iterations
    alpha = alpha_init * np.exp(-t / tau)
    sigma = max(sigma_init * np.exp(-t / tau), 0.5)
    return alpha, sigma


def project_weights_pca(weights, pca):
    """
    Helper function to use PCA on high-D weights for visualization in 2D space.
    """
    gx, gy, d = weights.shape
    return pca.transform(weights.reshape(-1, d)).reshape(gx, gy, 2)

