def main():
    GRID_X = 10       # SOM Rows
    GRID_Y = 10       # SOM Columns
    N_EPOCHS = 3      # Number of times we go through the entire dataset during training
    ALPHA_INIT = 0.5  # Initial learning rate
    SIGMA_INIT = 5.0  # Initial neighbourhood radius
    VIZ_EVERY = 5     # Visualization frequency (for the matplotlib animation)

    X, y, target_names = load_and_preprocess()
    n_samples, input_dim = X.shape
    n_iterations = N_EPOCHS * n_samples

    pca = PCA(n_components=2) # PCA down to 2D
    pca.fit(X) # Fit PCA on the original data to get the projection matrix, which will be used for both data and weights visualization
    X_pca = pca.transform(X)

    weights = initialize_weights(GRID_X, GRID_Y, input_dim)

    fig, ax = plt.subplots(figsize=(10, 8))
    fig.patch.set_facecolor('#0f0f1a')
    plt.ion()
    plt.show()

    t = 0
    rng = np.random.default_rng(0)
    for epoch in range(N_EPOCHS):
        indices = rng.permutation(n_samples)
        for idx in indices:
            x = X[idx]
            alpha, sigma = decay_parameters(t, n_iterations, ALPHA_INIT, SIGMA_INIT)
            bmu_idx = find_bmu(weights, x)

            if t % VIZ_EVERY == 0:
                h = compute_neighbourhood(GRID_X, GRID_Y, bmu_idx, sigma)
                weights_pca = project_weights_pca(weights, pca)
                x_pca = pca.transform(x.reshape(1, -1))[0]
                plot_som_state(ax, X_pca, y, weights_pca, bmu_idx, x_pca,
                               GRID_X, GRID_Y, h, t, alpha, sigma, target_names)
                fig.canvas.draw()
                plt.pause(0.125)

            weights = update_weights(weights, x, bmu_idx, alpha, sigma)
            t += 1

    plt.ioff()
    plt.close(fig)

    plot_final_result(X, X_pca, y, weights, pca, GRID_X, GRID_Y, target_names)


if __name__ == '__main__':
    main()
